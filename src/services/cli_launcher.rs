    #[test]
    fn messages_explain_path_state() {
        let installed = |on_path| LauncherOutcome::Installed {
            file: PathBuf::from("/home/me/.local/bin/lumen"),
            on_path,
            path_registered: false,
        };
        assert!(
            installed(Some(false))
                .message()
                .contains("is not on your PATH")
        );
        assert_eq!(
            installed(Some(true)).message(),
            "Installed the 'lumen' command at /home/me/.local/bin/lumen"
        );
        assert!(
            LauncherOutcome::Installed {
                file: PathBuf::from("lumen.cmd"),
                on_path: None,
                path_registered: true,
            }
            .message()
            .contains("open a new terminal")
        );
    }
